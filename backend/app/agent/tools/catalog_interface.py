from typing import Protocol, Any


class CatalogGateway(Protocol):
    async def find_offers(self, filters: dict[str, Any]) -> list[dict]: ...
    async def get_hotel(self, hotel_id: str) -> dict | None: ...
    async def get_hotels_by_ids(self, hotel_ids: list[str]) -> list[dict]: ...
    async def retrieve_reviews(self, query: str, hotel_ids: list[str], top_k: int = 5) -> list[dict]: ...
    async def retrieve_descriptions(self, query: str, hotel_ids: list[str], top_k: int = 5) -> list[dict]: ...
    async def find_transport(self, filters: dict[str, Any]) -> list[dict]: ...
