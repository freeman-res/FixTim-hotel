"""Контракт результата RAG-поиска. ReviewChunk — то, что возвращает retrieve_reviews.
AI-агент (участник №2) использует это как «обоснование» рекомендации:
цитата из отзыва + источник + оценка релевантности.
"""
from pydantic import BaseModel
class ReviewChunk(BaseModel):
    """
    Фрагмент отзыва, найденный по смыслу.
    """
    hotel_id: int
    """К какому отелю относится фрагмент."""
    text: str
    """Текст фрагмента отзыва."""
    source: str
    """Откуда взят фрагмент: "demo_reviews", "organizer_reviews" и т.п."""
    score: float
    """
    Релевантность запросу: больше = лучше.
    В текущей реализации score = 1 - distance (Chroma).
    Диапазон обычно 0..1, но не гарантирован строго.
    """