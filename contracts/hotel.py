"""
Контракты отеля и предложения проживания. Эти модели — договор между модулем Data/RAG (участник №3) и AI-агентом (участник №2).
Форма данных не меняется без согласования с командой.
"""
from pydantic import BaseModel, Field
from typing import Optional
class Hotel(BaseModel):
    """
    Базовая информация об отеле. Почти все поля Optional, потому что данные организаторов могут быть неполными.
    Отсутствие рейтинга или описания не должно ломать систему.
    """
    hotel_id: int
    """Уникальный идентификатор отеля. Обязателен — по нему связываются offers и reviews."""
    name: str
    """Название отеля. Обязательно."""
    city: Optional[str] = None
    """Город. Может отсутствовать."""
    price: Optional[float] = None
    """Базовая цена проживания (если указана в данных отеля, не в offer)."""
    rating: Optional[float] = None
    """Рейтинг отеля (например, 4.7). Может отсутствовать."""
    amenities: list[str] = Field(default_factory=list)
    """
    Список удобств: ["бассейн", "завтрак", "wi-fi"]. default_factory=list, а не [], чтобы у каждого экземпляра был свой список.
    """
    description: Optional[str] = None
    """Текстовое описание отеля. Используется в RAG-поиске."""
    location: Optional[str] = None
    """Расположение (например, "Центр Сочи"). Может отсутствовать."""


class Offer(BaseModel):
    """
    Конкретное предложение проживания: отель + даты + цена + доступность.
    Один отель может иметь несколько offers (разные даты, разные цены).
    """
    offer_id: int
    """Уникальный идентификатор предложения. Обязателен."""
    hotel_id: int
    """К какому отелю относится. Связь с Hotel.hotel_id. Обязателен."""
    check_in: Optional[str] = None
    """Дата заезда в формате ISO (YYYY-MM-DD) или как пришло от организаторов."""
    check_out: Optional[str] = None
    """Дата выезда."""
    guests: Optional[int] = None
    """Количество гостей, на которое рассчитано предложение."""
    total_price: Optional[float] = None
    """Полная стоимость проживания. По ТЗ возвращаем, если доступна."""
    available: Optional[bool] = None
    """
    Доступность номера.По тз None означает «неизвестно».
    """
    source: str = "unknown"
    """Источник данных: "demo", "csv", "api", "organizer" и т.п."""